// Postgres (production) schema + migrations, derived from prisma/schema.prisma (SQLite, local dev).
//
//   node scripts/prisma-postgres.mjs check            fail if prisma/postgres/schema.prisma is stale
//   node scripts/prisma-postgres.mjs migrate <name>   write a new Postgres migration + refresh the snapshot
//
// prisma/postgres/schema.prisma is a committed snapshot of what prisma/postgres/migrations produce,
// so new migrations are diffs between two schema files: no Postgres instance needed.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SOURCE = "prisma/schema.prisma";
const SNAPSHOT = "prisma/postgres/schema.prisma";
const MIGRATIONS = "prisma/postgres/migrations";

function postgresSchema() {
  const src = readFileSync(SOURCE, "utf8");
  const out = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
  if (out === src) throw new Error(`Could not find provider = "sqlite" in ${SOURCE}`);
  return `// GENERATED from ${SOURCE} by scripts/prisma-postgres.mjs. Do not edit by hand.\n${out}`;
}

const [, , command, name] = process.argv;

if (command === "check") {
  if (!existsSync(SNAPSHOT) || readFileSync(SNAPSHOT, "utf8") !== postgresSchema()) {
    console.error(`${SNAPSHOT} is out of date with ${SOURCE}.\nRun: npm run db:migrate:pg -- <migration_name>`);
    process.exit(1);
  }
  console.log("Postgres schema snapshot is up to date.");
} else if (command === "migrate") {
  if (!name || !/^[a-z0-9_]+$/.test(name)) throw new Error("Usage: npm run db:migrate:pg -- <snake_case_name>");
  const next = postgresSchema();
  const tmp = join(tmpdir(), `settle-pg-${Date.now()}.prisma`);
  writeFileSync(tmp, next);
  const from = existsSync(SNAPSHOT) ? ["--from-schema-datamodel", SNAPSHOT] : ["--from-empty"];
  const sql = execFileSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["prisma", "migrate", "diff", ...from, "--to-schema-datamodel", tmp, "--script"],
    { encoding: "utf8", shell: process.platform === "win32" },
  );
  rmSync(tmp);
  if (!sql.trim() || /This is an empty migration/.test(sql)) {
    console.log("No schema changes; nothing to do.");
    process.exit(0);
  }
  const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const dir = join(MIGRATIONS, `${stamp}_${name}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "migration.sql"), sql);
  if (!existsSync(join(MIGRATIONS, "migration_lock.toml"))) {
    writeFileSync(join(MIGRATIONS, "migration_lock.toml"), '# Please do not edit this file manually\nprovider = "postgresql"\n');
  }
  writeFileSync(SNAPSHOT, next);
  console.log(`Wrote ${dir}/migration.sql and refreshed ${SNAPSHOT}`);
} else {
  console.error("Usage: node scripts/prisma-postgres.mjs check | migrate <name>");
  process.exit(1);
}
